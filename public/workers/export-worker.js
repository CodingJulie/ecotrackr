self.onmessage = function (e) {
    const {
        entries,
        format,
        userProfile,
        locale = 'en',
        labels = {},
    } = e.data;

    const t = {
        noData: labels.noData || 'No data to export',
        user: labels.user || 'User',
        date: labels.date || 'Date',
        category: labels.category || 'Category',
        activity: labels.activity || 'Activity',
        value: labels.value || 'Value',
        co2e: labels.co2e || 'CO₂e (kg)',
        reportTitle: labels.reportTitle || 'Environmental Report',
        totalCo2: labels.totalCo2 || 'kg CO₂e (total)',
        avgCo2: labels.avgCo2 || 'kg CO₂e (average)',
        totalEntries: labels.totalEntries || 'total entries',
        byCategory: labels.byCategory || 'By category',
        emissions: labels.emissions || 'Emissions (kg CO₂e)',
        details: labels.details || 'Entry details',
        moreEntries: labels.moreEntries || '... and {{count}} more entries',
        footer: labels.footer || 'Report generated by EcoTrackr · {{date}}',
        unsupportedFormat: labels.unsupportedFormat || 'Unsupported export format',
    };

    if (!entries || entries.length === 0) {
        self.postMessage({ error: t.noData });
        return;
    }

    const totalCO2 = entries.reduce((sum, entry) => sum + (entry.co2e || 0), 0);
    const byCategory = {};
    for (const entry of entries) {
        byCategory[entry.category] = (byCategory[entry.category] || 0) + (entry.co2e || 0);
    }

    const isRu = String(locale).toLowerCase().startsWith('ru');
    const delimiter = isRu ? ';' : ',';

    const formatDate = (dateStr) => {
        if (!dateStr) return '';
        try {
            const date = new Date(dateStr);
            if (isNaN(date.getTime())) return dateStr;
            return new Intl.DateTimeFormat(locale, {
                day: '2-digit',
                month: '2-digit',
                year: 'numeric',
            }).format(date);
        } catch {
            return dateStr;
        }
    };

    const formatNumber = (num) => {
        if (num === null || num === undefined || isNaN(num)) return '';
        const fixed = Number(num).toFixed(2);
        return isRu ? fixed.replace('.', ',') : fixed;
    };

    const interpolate = (template, vars) =>
        String(template).replace(/\{\{(\w+)\}\}/g, (_, key) =>
            vars[key] !== undefined && vars[key] !== null ? String(vars[key]) : ''
        );

    const escapeHtml = (value) =>
        String(value ?? '')
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;');

    if (format === 'csv') {
        const headers = [t.date, t.category, t.activity, t.value, t.co2e];
        const rows = entries.map((entry) => [
            formatDate(entry.date),
            entry.category || '',
            entry.activity || '',
            formatNumber(entry.value),
            formatNumber(entry.co2e),
        ]);

        let csvContent = headers.join(delimiter) + '\n';

        for (const row of rows) {
            const escapedRow = row.map((cell) => {
                if (typeof cell === 'string') {
                    if (cell.includes(delimiter) || cell.includes('"') || cell.includes('\n')) {
                        return `"${cell.replace(/"/g, '""')}"`;
                    }
                    return cell;
                }
                return cell;
            });
            csvContent += escapedRow.join(delimiter) + '\n';
        }

        // BOM so Excel opens Cyrillic CSV correctly
        self.postMessage({ data: '\uFEFF' + csvContent, format: 'csv' });
    } else if (format === 'json') {
        const exportData = {
            exportedAt: new Date().toISOString(),
            user: userProfile,
            summary: {
                totalCO2: Math.round(totalCO2),
                entriesCount: entries.length,
                categories: Object.keys(byCategory),
                averageCO2: Math.round(totalCO2 / entries.length),
            },
            entries: entries.map((entry) => ({
                ...entry,
                date: formatDate(entry.date),
                value: Number(entry.value ?? 0),
                co2e: Number(entry.co2e ?? 0),
            })),
        };
        self.postMessage({ data: JSON.stringify(exportData, null, 2), format: 'json' });
    } else if (format === 'html') {
        const reportDate = new Date().toLocaleDateString(locale, {
            day: 'numeric',
            month: 'long',
            year: 'numeric',
        });
        const footerDate = new Date().toLocaleString(locale);
        const userName = escapeHtml(userProfile?.name || t.user);
        const userEmail = escapeHtml(userProfile?.email || '');

        const html = `
            <!DOCTYPE html>
            <html lang="${escapeHtml(locale)}">
            <head>
                <meta charset="UTF-8">
                <title>${escapeHtml(t.reportTitle)}</title>
                <style>
                    * { box-sizing: border-box; }
                    body { font-family: Arial, sans-serif; padding: 40px; max-width: 1000px; margin: 0 auto; background: #f9fafb; }
                    .container { background: white; border-radius: 16px; padding: 40px; box-shadow: 0 4px 6px rgba(0,0,0,0.1); }
                    h1 { color: #10b981; font-size: 28px; margin-top: 0; }
                    .header { display: flex; justify-content: space-between; align-items: center; border-bottom: 3px solid #10b981; padding-bottom: 16px; margin-bottom: 24px; }
                    .stats { display: grid; grid-template-columns: repeat(3, 1fr); gap: 16px; margin-bottom: 24px; }
                    .stat-card { background: #f3f4f6; border-radius: 12px; padding: 16px; text-align: center; }
                    .stat-card .value { font-size: 28px; font-weight: bold; color: #059669; }
                    .stat-card .label { font-size: 13px; color: #6b7280; margin-top: 4px; }
                    table { width: 100%; border-collapse: collapse; margin: 16px 0; font-size: 14px; }
                    th { background: #10b981; color: white; padding: 10px 16px; text-align: left; }
                    td { padding: 8px 16px; border-bottom: 1px solid #e5e7eb; }
                    .footer { margin-top: 32px; padding-top: 16px; border-top: 1px solid #e5e7eb; text-align: center; color: #9ca3af; font-size: 12px; }
                </style>
            </head>
            <body>
                <div class="container">
                    <div class="header">
                        <div>
                            <h1>🌿 ${escapeHtml(t.reportTitle)}</h1>
                            <p style="color: #6b7280; margin: 0;">EcoTrackr · ${escapeHtml(reportDate)}</p>
                        </div>
                        <div style="text-align: right;">
                            <p style="margin: 0; font-weight: 500;">${userName}</p>
                            <p style="margin: 0; font-size: 13px; color: #6b7280;">${userEmail}</p>
                        </div>
                    </div>

                    <div class="stats">
                        <div class="stat-card">
                            <div class="value">${Math.round(totalCO2)}</div>
                            <div class="label">${escapeHtml(t.totalCo2)}</div>
                        </div>
                        <div class="stat-card">
                            <div class="value">${Math.round(totalCO2 / entries.length)}</div>
                            <div class="label">${escapeHtml(t.avgCo2)}</div>
                        </div>
                        <div class="stat-card">
                            <div class="value">${entries.length}</div>
                            <div class="label">${escapeHtml(t.totalEntries)}</div>
                        </div>
                    </div>

                    <h2>${escapeHtml(t.byCategory)}</h2>
                    <table>
                        <thead><tr><th>${escapeHtml(t.category)}</th><th style="text-align: right;">${escapeHtml(t.emissions)}</th></tr></thead>
                        <tbody>
                            ${Object.entries(byCategory)
                                .sort((a, b) => b[1] - a[1])
                                .map(
                                    ([cat, val]) => `
                                    <tr>
                                        <td>${escapeHtml(cat)}</td>
                                        <td style="text-align: right; font-weight: 600; color: #059669;">${Math.round(val)}</td>
                                    </tr>
                                `
                                )
                                .join('')}
                        </tbody>
                    </table>

                    <h2>${escapeHtml(t.details)}</h2>
                    <table>
                        <thead><tr><th>${escapeHtml(t.date)}</th><th>${escapeHtml(t.category)}</th><th>${escapeHtml(t.activity)}</th><th style="text-align: right;">${escapeHtml(t.co2e)}</th></tr></thead>
                        <tbody>
                            ${entries
                                .slice(0, 30)
                                .map(
                                    (entry) => `
                                <tr>
                                    <td>${escapeHtml(formatDate(entry.date))}</td>
                                    <td>${escapeHtml(entry.category)}</td>
                                    <td>${escapeHtml(entry.activity)}</td>
                                    <td style="text-align: right; font-weight: 500;">${Number(entry.co2e ?? 0).toFixed(2)}</td>
                                </tr>
                            `
                                )
                                .join('')}
                            ${
                                entries.length > 30
                                    ? `
                                <tr><td colspan="4" style="text-align: center; color: #6b7280; font-style: italic;">${escapeHtml(
                                    interpolate(t.moreEntries, { count: entries.length - 30 })
                                )}</td></tr>
                            `
                                    : ''
                            }
                        </tbody>
                    </table>

                    <div class="footer">
                        ${escapeHtml(interpolate(t.footer, { date: footerDate }))}
                    </div>
                </div>
            </body>
            </html>
        `;
        self.postMessage({ data: html, format: 'html' });
    } else {
        self.postMessage({ error: t.unsupportedFormat });
    }
};
